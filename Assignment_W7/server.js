/**
 * server.js — Task Management API (Security Hardened)
 * Week 7: HTTPS/TLS + express-mongo-sanitize + Security Headers
 * Author: Aayush Kathiriya
 *
 * Security measures applied:
 *   1. express-mongo-sanitize  — NoSQL injection prevention
 *   2. HTTPS via mkcert certs  — TLS encryption in transit
 *   3. Security headers        — X-Content-Type-Options, X-Frame-Options, etc.
 *   4. Input validation        — enforced in route handlers
 */

const express      = require('express');
const https        = require('https');
const http         = require('http');
const fs           = require('fs');
const path         = require('path');
const mongoSanitize = require('express-mongo-sanitize');

const app = express();

// ── 1. Body Parsers ──────────────────────────────────────────────────────────
app.use(express.json());
app.use(express.urlencoded({ extended: false }));

// ── 2. NoSQL Injection Prevention ────────────────────────────────────────────
// MUST be placed BEFORE route definitions.
// Strips keys containing '$' or '.' from req.body, req.params, req.query.
// Example blocked payload: { "email": { "$gt": "" }, "password": { "$gt": "" } }
app.use(
  mongoSanitize({
    replaceWith: '_',        // replace malicious keys with '_' instead of deleting
    onSanitize: ({ req, key }) => {
      console.warn(`[SECURITY] Sanitized key '${key}' in ${req.method} ${req.originalUrl}`);
    },
  })
);

// ── 3. Basic Security Headers ────────────────────────────────────────────────
app.use((req, res, next) => {
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.setHeader('X-Frame-Options', 'DENY');
  res.setHeader('X-XSS-Protection', '1; mode=block');
  res.setHeader('Strict-Transport-Security', 'max-age=31536000; includeSubDomains');
  res.setHeader('X-API-Version', '2.0.0');
  res.setHeader('X-RMM-Level', '2');
  next();
});

// ── 4. Routes ────────────────────────────────────────────────────────────────
const taskRoutes = require('./routes/tasks');
app.use('/tasks', taskRoutes);

// ── 5. Root Info ──────────────────────────────────────────────────────────────
app.get('/', (req, res) => {
  res.status(200).json({
    name: 'Task Management REST API',
    version: '2.0.0',
    rmm_level: 2,
    security: {
      nosql_injection_prevention: 'express-mongo-sanitize (active)',
      transport_security: 'HTTPS/TLS via mkcert (port 5443)',
      security_headers: ['X-Content-Type-Options', 'X-Frame-Options', 'X-XSS-Protection', 'Strict-Transport-Security'],
    },
    endpoints: {
      'GET    /tasks':     'Retrieve all tasks',
      'POST   /tasks':     'Create a new task',
      'GET    /tasks/:id': 'Retrieve a single task',
      'PUT    /tasks/:id': 'Fully replace a task',
      'PATCH  /tasks/:id': 'Partially update a task',
      'DELETE /tasks/:id': 'Delete a task',
    },
  });
});

// ── 6. 404 & Error Handlers ───────────────────────────────────────────────────
app.use((req, res) => {
  res.status(404).json({ success: false, message: `Route '${req.originalUrl}' not found.` });
});

app.use((err, req, res, next) => {
  console.error(err.stack);
  res.status(500).json({ success: false, message: 'Internal Server Error.' });
});

// ── 7. Start Servers ──────────────────────────────────────────────────────────
const HTTP_PORT  = process.env.PORT || 3000;
const HTTPS_PORT = process.env.HTTPS_PORT || 5443;

// Always start HTTP server
http.createServer(app).listen(HTTP_PORT, () => {
  console.log(`\n[HTTP]  Task Management API running on http://localhost:${HTTP_PORT}`);
});

// Start HTTPS server only if certificates exist
const certPath = path.join(__dirname, 'localhost.pem');
const keyPath  = path.join(__dirname, 'localhost-key.pem');

if (fs.existsSync(certPath) && fs.existsSync(keyPath)) {
  const sslOptions = {
    key:  fs.readFileSync(keyPath),
    cert: fs.readFileSync(certPath),
  };
  https.createServer(sslOptions, app).listen(HTTPS_PORT, () => {
    console.log(`[HTTPS] Task Management API running on https://localhost:${HTTPS_PORT}`);
    console.log(`[TLS]   Certificate: localhost.pem (generated by mkcert)\n`);
  });
} else {
  console.warn(`[WARN]  HTTPS cert not found. Run: mkcert localhost`);
  console.warn(`[WARN]  HTTPS server will not start until certs are present.\n`);
}
